# ==============================================================================
# PART II: DATA QUALITY CLEANING AND FEATURE ENGINEERING
# ==============================================================================
print("\n=== PART II: DATA QUALITY & FEATURE ENGINEERING ===")

dq_log = []

# 1. Remove Duplicates
dup_count = df["Request_ID"].duplicated().sum()
if dup_count > 0:
    df = df.drop_duplicates(subset=["Request_ID"], keep="first")
dq_log.append(f"Duplicates: Removed {dup_count} duplicate Request_ID records.")

# 2. Standardize Dates
df["Submission_Date"] = pd.to_datetime(df["Submission_Date"], errors="coerce")
invalid_dates = df["Submission_Date"].isna().sum()
if invalid_dates > 0:
    df = df.dropna(subset=["Submission_Date"])
dq_log.append(
    f"Invalid Dates: Dropped {invalid_dates} rows with invalid dates."
)

# 3. Clean Negative Numeric Values
num_cols_to_check = ["Queue_Length", "Processing_Days", "SLA_Days"]
for col in num_cols_to_check:
    neg_mask = df[col] < 0
    neg_count = neg_mask.sum()
    if neg_count > 0:
        df.loc[neg_mask, col] = np.nan
        dq_log.append(
            f"Negative Values: Converted {neg_count} negative entries in {col} to NaN."
        )

# 4. Standardize Categorical Text Formatting
text_cols = [
    "Service_Type",
    "Requester_Type",
    "Requested_Channel",
    "Priority",
    "Required_Documents_Complete",
    "Status",
]
for col in text_cols:
    if col in df.columns:
        df[col] = df[col].astype(str).str.strip().str.title()

# 5. Feature Engineering
# Feature 1: Submission_Weekday
df["Submission_Weekday"] = df["Submission_Date"].dt.day_name()

# Feature 2: Queue_Category (Low: 0-5, Medium: 6-15, High: >15)
bins = [-1, 5, 15, float("inf")]
labels = ["Low", "Medium", "High"]
df["Queue_Category"] = pd.cut(df["Queue_Length"], bins=bins, labels=labels)

# Feature 3: SLA_Breached Target (Only for Completed requests with valid processing days)
completed_mask = (
    (df["Status"] == "Completed")
    & (df["Processing_Days"].notna())
    & (df["SLA_Days"].notna())
)

df["SLA_Breached"] = np.nan
df.loc[completed_mask, "SLA_Breached"] = (
    df.loc[completed_mask, "Processing_Days"]
    > df.loc[completed_mask, "SLA_Days"]
).astype(int)

# Separate into full cleaned dataset and filtered modeling subset
df_cleaned = df.copy()
